def cove():
    fig, ax = canvas('论文2｜同一图像，怎样变成多个任务的预测？',
                     '三个视觉专家都提取特征；六候选连续加权，不是稀疏Top-k。', 9.1)
    box(ax, 4, 7.43, '同一图像 → 三个冻结视觉专家',
        'SAM、DINOv2、V-JEPA 2.1各取第3、6、9、12块特征', h=1.12)
    box(ax, 4, 6.11, '可训练对齐层', '把各模型特征映射到共同维度和图像网格')
    arrow(ax, 4, 6.85, 4, 6.58)
    box(ax, 2.08, 4.76, '保留原始候选', '三个对齐后的专家特征', w=3.48, h=1.04, palette=BLUE)
    box(ax, 5.92, 4.76, '三个两两组合模块', '每对形成一个组合特征', w=3.48, h=1.04, palette=PURPLE)
    for x in [2.08, 5.92]:
        ax.plot([4, 4, x], [5.64, 5.48, 5.48], color='#586371', lw=1.4)
        arrow(ax, x, 5.48, x, 5.30)
    box(ax, 4, 3.45, '六个候选特征', '三个原始候选＋三个组合候选', palette=PURPLE)
    for x in [2.08, 5.92]:
        arrow(ax, x, 4.22, x, 3.92)
    box(ax, 4, 2.23, '路由器按任务、图像位置产生六个权重',
        '读取图像信息与任务描述；对六个候选加权融合', palette=ORANGE)
    arrow(ax, 4, 2.98, 4, 2.70)
    box(ax, 4, 1.01, '对应任务的预测头', '输出分割、深度、表面方向或边界结果', palette=GREEN)
    arrow(ax, 4, 1.76, 4, 1.48)
    label(ax, .375, .28, '训练对齐层、组合模块、路由器和预测头；视觉专家冻结。', 14.5, va='center')
    save(fig, 'Method_02_COVE_network')


