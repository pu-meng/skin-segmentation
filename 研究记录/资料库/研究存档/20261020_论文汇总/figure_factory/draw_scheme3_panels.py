def panel(name,title,subtitle,cards,footer):
    y=100; parts=[]
    def text(x,y,s,size=20,bold=False):
        parts.append(f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{700 if bold else 400}">{escape(s)}</text>')
    text(24,38,title,27,True); text(24,72,subtitle,19)
    for i,(heading,lines,color) in enumerate(cards):
        h=54+29*len(lines)
        parts.append(f'<rect x="24" y="{y}" width="802" height="{h}" rx="10" fill="{COL[color]}" stroke="{INK}" stroke-width="1.4"/>')
        text(42,y+33,heading,22,True)
        for j,line in enumerate(lines): text(42,y+64+j*29,line)
        y+=h
        if i<len(cards)-1 and name!='方案3_设计边界':
            parts.append(f'<path d="M425 {y+3} V{y+24}" fill="none" stroke="{INK}" stroke-width="2" marker-end="url(#arr)"/>')
        y+=32
    for line in footer: text(24,y+2,line,18); y+=27
    height=y+12
    svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="850" height="{height}" viewBox="0 0 850 {height}"><defs><marker id="arr" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0 L8 4 L0 8" fill="{INK}"/></marker></defs><rect width="850" height="{height}" fill="white"/><g fill="{INK}" font-family="Microsoft YaHei, Noto Sans CJK SC, sans-serif">'+''.join(parts)+'</g></svg>'
    p=ROOT/(name+'.svg'); p.write_text(svg,encoding='utf-8'); ET.parse(p)
    return {'name':name,'height':height,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}

